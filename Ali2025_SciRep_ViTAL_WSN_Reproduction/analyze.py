"""Tables (results/summary.md) and figures (figures/*.png) for the ViTAL reproduction."""
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from vital_repro import E0, EELEC

NS = [100, 200, 300, 400, 500]
rows = json.load(open("results/runs.json"))
paper = json.load(open("paper_digitized/paper_values.json"))
dq = {d["name"]: d for d in json.load(open("results/deployment_quality.json"))}
os.makedirs("figures", exist_ok=True)

# paper label -> (protocol, deployment) in this code
STATIC = {"LEACH_random": ("LEACH", "random"), "LEACH_optimal": ("LEACH", "hsa"),
          "EE-LEACH_random": ("EE-LEACH*", "random"), "EE-LEACH_optimal": ("EE-LEACH*", "hsa"),
          "I-LEACH_random": ("I-LEACH*", "random"), "I-LEACH_optimal": ("I-LEACH*", "hsa"),
          "4F_random": ("4F", "random"), "ViTAL": ("ViTAL", "hsa")}
MOBILE = {"LEACH": "LEACH", "EE-LEACH": "EE-LEACH*", "I-LEACH": "I-LEACH*", "ViTAL": "ViTAL"}
METRIC = {"FND": "FND", "LND": "LND", "packets": "packets", "residual": "res1000"}


def sel(proto, kind, N, L, mobile=False, wname=None):
    return [r for r in rows if r["protocol"] == proto and r["deploy"] == kind and r["N"] == N
            and r["L"] == L and r.get("mobile", False) == mobile and r.get("wname") == wname]


def arr(R, k):
    return np.array([np.nan if r[k] is None else r[k] for r in R], float)


def mean_sd(R, k):
    v = arr(R, k)
    return np.nanmean(v), np.nanstd(v, ddof=1)


def fmt(m, s, k):
    return f"{m:.3f} ± {s:.3f}" if k == "res1000" else f"{m:.0f} ± {s:.0f}"


md = ["# ViTAL reproduction: results (auto-generated by analyze.py)\n"]

# --- deployment quality
md.append("## 1. Deployment phase (HSA vs random), mean over 30 deployments\n")
md.append("| N | coverage cr random | coverage cr HSA | dmin random (m) | dmin HSA (m) | max possible cr (disjoint disks) |\n|---|---|---|---|---|---|")
for N in NS:
    g = lambda kind, key: np.mean([dq[f"{kind}_{N}_{s}"][key] for s in range(30)])
    md.append(f"| {N} | {g('random','cr'):.3f} | {g('hsa','cr'):.3f} | {g('random','dmin'):.2f} | {g('hsa','dmin'):.2f} | {min(1, N*np.pi*25/1e4):.3f} |")

# --- energy feasibility bound
md.append("\n## 2. Energy feasibility bound\n")
md.append("If every alive node sends one L-bit packet per round, a node can never live longer than E0 / (L · Eelec) rounds, even at zero distance and never serving as CH.\n")
md.append("| Packet size L | Upper bound on any node's lifetime (rounds) | Paper ViTAL FND range | Paper ViTAL LND range |\n|---|---|---|---|")
for L in (800, 4000):
    md.append(f"| {L} bits | {E0/(L*EELEC):.0f} | {min(paper['static']['FND']['ViTAL'])}–{max(paper['static']['FND']['ViTAL'])} | {min(paper['static']['LND']['ViTAL'])}–{max(paper['static']['LND']['ViTAL'])} |")


def static_table(L):
    out = [f"\n## 3{'a' if L == 800 else 'b'}. Static scenario, L = {L} bits (paper Fig. 6). Reproduction mean ± sd over 30 runs; paper value digitised\n"]
    for pm, k in METRIC.items():
        out.append(f"### {pm}\n\n| Series | " + " | ".join(f"N={N} paper / repro" for N in NS) + " |\n|---|" + "---|" * len(NS))
        for lab, (p, kind) in STATIC.items():
            cells = []
            for i, N in enumerate(NS):
                m, s = mean_sd(sel(p, kind, N, L), k)
                cells.append(f"{paper['static'][pm][lab][i]} / {fmt(m, s, k)}")
            out.append(f"| {lab}{'*' if 'LEACH' in lab and not lab.startswith('LEACH') else ''} | " + " | ".join(cells) + " |")
        out.append("")
    return out


md += static_table(800)
md += static_table(4000)


def improvements(L, mobile):
    src = paper["mobile" if mobile else "static"]
    claims = paper["text_claims_percent"]["mobile" if mobile else "static_vs_random_baselines"]
    base = [("LEACH", "LEACH"), ("EE-LEACH*", "EE-LEACH"), ("I-LEACH*", "I-LEACH")]
    out = [f"\n### ViTAL improvement over baselines, {'mobile' if mobile else 'static, random-deployed baselines'}, L = {L}\n",
           "| Metric | Baseline | Paper text | Paper figure (V−B)/V | Paper figure (V−B)/B | Repro (V−B)/V | Repro (V−B)/B |",
           "|---|---|---|---|---|---|---|"]
    for pm, k in METRIC.items():
        for (p, plab), claim in zip(base, claims[pm]):
            key = plab if mobile else f"{plab}_random"
            PV, PB = np.array(src[pm]["ViTAL"], float), np.array(src[pm][key], float)
            V = np.array([np.nanmean(arr(sel("ViTAL", "hsa", N, L, mobile), k)) for N in NS])
            B = np.array([np.nanmean(arr(sel(p, "hsa" if mobile else "random", N, L, mobile), k)) for N in NS])
            out.append(f"| {pm} | {p} | {claim}% | {100*np.mean((PV-PB)/PV):.0f}% | {100*np.mean((PV-PB)/PB):+.0f}% | "
                       f"{100*np.mean((V-B)/V):.0f}% | {100*np.mean((V-B)/B):+.0f}% |")
    return out


md.append("\n## 4. Headline improvement claims\n")
md.append("The paper's percentages match (V−B)/V computed from its own figures, i.e. the gain divided by ViTAL's value. The usual definition is (V−B)/B.\n")
for L in (800, 4000):
    md += improvements(L, False)
for L in (800, 4000):
    md += improvements(L, True)

# --- mobile tables
for L in (800, 4000):
    md.append(f"\n## 5{'a' if L == 800 else 'b'}. Mobile sink, L = {L} (paper Fig. 7)\n")
    for pm, k in METRIC.items():
        md.append(f"### {pm}\n\n| Series | " + " | ".join(f"N={N} paper / repro" for N in NS) + " |\n|---|" + "---|" * len(NS))
        for lab, p in MOBILE.items():
            cells = [f"{paper['mobile'][pm][lab][i]} / {fmt(*mean_sd(sel(p, 'hsa', N, L, True), k), k)}" for i, N in enumerate(NS)]
            md.append(f"| {p} | " + " | ".join(cells) + " |")
        md.append("")

# --- sensitivity
md.append("\n## 6. Sensitivity of 4F / ViTAL to the unreported weights w1..w4 and to the distance term (L = 800, 10 runs)\n")
md.append("| Protocol | Variant | N | FND | LND | Packets | Residual @1000 |\n|---|---|---|---|---|---|---|")
for p, kind in (("4F", "random"), ("ViTAL", "hsa")):
    for wn in ("equal", "energy_only", "neigh_only", "dist_only", "snr_only", "energy_heavy", "equal_inverted_dist"):
        for N in (100, 300, 500):
            R = sel(p, kind, N, 800, wname=wn)
            md.append(f"| {p} | {wn} | {N} | " + " | ".join(fmt(*mean_sd(R, k), k) for k in ("FND", "LND", "packets", "res1000")) + " |")
# --- post-hoc robustness checks (extra_experiments.py)
ex = json.load(open("results/extra.json"))
md.append("\n## 7. Post-hoc check: ViTAL without the CDS restriction (4F selection on HSA deployment), 30 runs\n")
md.append("| L | Metric | " + " | ".join(f"N={N}" for N in NS) + " |\n|---|---|" + "---|" * len(NS))
for L in (800, 4000):
    for k in ("FND", "LND"):
        cells = []
        for N in NS:
            v = arr([r for r in ex["nocds"] if r["L"] == L and r["N"] == N], k)
            b = np.nanmean(arr(sel("LEACH", "random", N, L), k))
            cells.append(f"{np.nanmean(v):.0f} (LEACH_random {b:.0f})")
        md.append(f"| {L} | {k} | " + " | ".join(cells) + " |")
md.append("\n## 8. Post-hoc check: can any packet size L and Eelec fit the paper's LEACH numbers and still allow ViTAL's lifetimes?\n")
md.append("LEACH, random deployment, N = 100, 5 runs each. Paper: LEACH_random FND 560, LND 1180; ViTAL FND 3000. "
          "'Fits' means LEACH FND and LND both within ±25% of the paper and the lifetime cap E0/(L·Eelec) ≥ 3000.\n")
md.append("| L (bits) | Eelec (nJ/bit) | LEACH FND | LND | Lifetime cap | LEACH FND fits | LEACH LND fits | Cap ≥ 3000 | All three |\n|---|---|---|---|---|---|---|---|---|")
for L in sorted({r["L"] for r in ex["scan"]}):
    for e in sorted({r["Eelec"] for r in ex["scan"]}):
        R = [r for r in ex["scan"] if r["L"] == L and r["Eelec"] == e]
        f, l, cap = np.mean([r["FND"] for r in R]), np.mean([r["LND"] for r in R]), R[0]["bound"]
        a, b_, c = abs(f - 560) <= 140, abs(l - 1180) <= 295, cap >= 3000
        md.append(f"| {L} | {e*1e9:.0f} | {f:.0f} | {l:.0f} | {cap:.0f} | {'yes' if a else 'no'} | {'yes' if b_ else 'no'} | {'yes' if c else 'no'} | {'**yes**' if a and b_ and c else 'no'} |")
open("results/summary.md", "w").write("\n".join(md) + "\n")

# --- figures: paper (left) vs reproduction (right) for each metric
COL = {"LEACH": "#2a78d6", "EE-LEACH": "#eb6834", "I-LEACH": "#1baf7a", "ViTAL": "#e87ba4"}
plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False,
                     "axes.grid": True, "grid.color": "#e4e3df", "grid.linewidth": 0.6})


def fam(lab):
    return "ViTAL" if lab in ("ViTAL", "4F_random") else lab.split("_")[0]


def fig_static(L, fname):
    fig, axs = plt.subplots(2, 4, figsize=(14, 6.4))
    for c, (pm, k) in enumerate(METRIC.items()):
        for lab, (p, kind) in STATIC.items():
            ls = "-" if (kind == "hsa") else "--"
            axs[0, c].plot(NS, paper["static"][pm][lab], ls, marker="o", ms=3, color=COL[fam(lab)], lw=1.6, label=lab)
            m = [mean_sd(sel(p, kind, N, L), k) for N in NS]
            axs[1, c].errorbar(NS, [a for a, _ in m], yerr=[b for _, b in m], fmt=ls, marker="o", ms=3,
                               color=COL[fam(lab)], lw=1.6, capsize=2, label=lab)
        axs[0, c].set_title(f"Paper Fig. 6: {pm}", fontsize=9)
        axs[1, c].set_title(f"Reproduction (L={L}): {pm}", fontsize=9)
        axs[1, c].set_xlabel("No. of nodes")
    fig.legend(*axs[0, 0].get_legend_handles_labels(), loc="lower center", ncol=8, fontsize=7.5, frameon=False,
               bbox_to_anchor=(0.5, 0.03))
    fig.text(0.01, 0.005, "Solid = HSA ('optimal') deployment, dashed = random. Starred baselines (EE-LEACH*, I-LEACH*) are reconstructions. Residual energy measured at round 1000.",
             fontsize=7, color="#52514e")
    fig.tight_layout(rect=(0, 0.07, 1, 1))
    fig.savefig(f"figures/{fname}", dpi=150)


def fig_mobile(L, fname):
    fig, axs = plt.subplots(2, 4, figsize=(14, 6.4))
    for c, (pm, k) in enumerate(METRIC.items()):
        for lab, p in MOBILE.items():
            axs[0, c].plot(NS, paper["mobile"][pm][lab], "-", marker="o", ms=3, color=COL[lab], lw=1.6, label=lab)
            m = [mean_sd(sel(p, "hsa", N, L, True), k) for N in NS]
            axs[1, c].errorbar(NS, [a for a, _ in m], yerr=[b for _, b in m], fmt="-", marker="o", ms=3,
                               color=COL[lab], lw=1.6, capsize=2, label=p)
        axs[0, c].set_title(f"Paper Fig. 7: {pm}", fontsize=9)
        axs[1, c].set_title(f"Reproduction (L={L}): {pm}", fontsize=9)
        axs[1, c].set_xlabel("No. of nodes")
    fig.legend(*axs[1, 0].get_legend_handles_labels(), loc="lower center", ncol=4, fontsize=8, frameon=False)
    fig.tight_layout(rect=(0, 0.05, 1, 1))
    fig.savefig(f"figures/{fname}", dpi=150)


fig_static(800, "R1_static_L800_vs_paper_fig6.png")
fig_static(4000, "R2_static_L4000_vs_paper_fig6.png")
fig_mobile(800, "R3_mobile_L800_vs_paper_fig7.png")
fig_mobile(4000, "R4_mobile_L4000_vs_paper_fig7.png")
