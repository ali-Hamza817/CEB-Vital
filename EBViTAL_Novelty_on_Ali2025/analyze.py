STY = {"LEACH (random)": ("#2a78d6", "--"), "LEACH (HSA)": ("#2a78d6", "-"), "ViTAL": ("#eb6834", "-"),
       "ViTAL-noCDS": ("#eb6834", "--"), "EB-ViTAL": ("#1baf7a", "-"), "EB -M1": ("#eda100", "-"),
       "EB -M2": ("#e87ba4", "-"), "EB -M3": ("#6250d6", "-"), "EB-ViTAL (random)": ("#1baf7a", "--")}


def panel_fig(labels, L, mobile, fname, title):
    fig, axs = plt.subplots(1, 4, figsize=(14, 3.6))
    for ax, (name, k) in zip(axs, list(MET.items())[:4]):
        for lab in labels:
            m = [np.nanmean(get(lab, N, L, mobile, k)) for N in NS]
            ci = [1.96 * np.nanstd(get(lab, N, L, mobile, k), ddof=1) / np.sqrt(30) for N in NS]
            c, ls = STY[lab]
            ax.errorbar(NS, m, yerr=ci, color=c, ls=ls, marker="o", ms=3, lw=1.8, capsize=2, label=lab)
        ax.set_title(name, fontsize=9)
        ax.set_xlabel("No. of nodes")
    fig.suptitle(title, fontsize=10)
    fig.legend(*axs[0].get_legend_handles_labels(), loc="lower center", ncol=len(labels), fontsize=8, frameon=False)
    fig.tight_layout(rect=(0, 0.08, 1, 0.95))
    fig.savefig(f"figures/{fname}", dpi=150)


panel_fig(MAIN, 800, False, "F1_static_L800.png", "Static sink at (5,5), L = 800 bits: mean ± 95% CI, 30 runs")
panel_fig(MAIN, 4000, False, "F2_static_L4000.png", "Static sink at (5,5), L = 4000 bits")
panel_fig(["LEACH (HSA)", "ViTAL", "EB-ViTAL"], 800, True, "F3_mobile_L800.png", "Mobile sink, L = 800 bits")
panel_fig(ABL, 800, False, "F4_ablation_L800.png", "Ablation of EB-ViTAL components, static, L = 800 bits")

# alive-nodes curve, N = 100, L = 800, static (30 seeds)
DEP = dict(np.load("results/deployments.npz"))


def deaths(a):
    proto, kind, s = a
    return simulate(proto, 100, s, xy=DEP[f"{kind}_100_{s}"], L=800)["deaths"]


curves = {}
with Pool(64) as pool:
    for lab, proto, kind in (("LEACH (HSA)", "LEACH", "hsa"), ("ViTAL", "ViTAL", "hsa"), ("EB-ViTAL", "EB-ViTAL", "hsa")):
        D = pool.map(deaths, [(proto, kind, s) for s in range(30)])
        t = np.arange(13000)
        curves[lab] = np.mean([100 - np.searchsorted(np.array(d), t, side="right") for d in D], 0)
fig, ax = plt.subplots(figsize=(6.4, 3.6))
for lab, y in curves.items():
    c, ls = STY[lab]
    ax.plot(np.arange(len(y)), y, ls, color=c, lw=2, label=lab)
ax.set_xlabel("Round")
ax.set_ylabel("Alive nodes (mean of 30 runs)")
ax.set_title("Alive nodes over time, N = 100, static, L = 800", fontsize=9)
ax.legend(frameon=False, fontsize=8)
fig.tight_layout()
fig.savefig("figures/F5_alive_nodes_N100.png", dpi=150)
