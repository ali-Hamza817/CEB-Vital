"""Hypothesis tests, tables (results/summary.md) and figures (figures/*.png) for EB-ViTAL."""
import json
import os
from multiprocessing import Pool

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
from scipy.stats import wilcoxon

from wsn_sim import simulate

NS = [100, 200, 300, 400, 500]
R = json.load(open("results/runs.json"))
os.makedirs("figures", exist_ok=True)
MAIN = ["LEACH (random)", "LEACH (HSA)", "ViTAL", "ViTAL-noCDS", "EB-ViTAL"]
ABL = ["EB-ViTAL", "EB -M1", "EB -M2", "EB -M3", "EB-ViTAL (random)"]
MET = {"FND": "FND", "HND": "HND", "LND": "LND", "readings/node": "readings", "packets": "packets", "residual@1000": "res1000"}


def get(label, N, L=800, mobile=False, key="FND"):
    S = sorted((r for r in R if r["label"] == label and r["N"] == N and r["L"] == L and r["mobile"] == mobile),
               key=lambda r: r["seed"])
    v = np.array([np.nan if r[key] is None else r[key] for r in S], float)
    return v / N if key == "readings" else v


def holm(p):
    p = np.asarray(p)
    o = np.argsort(p)
    adj = np.empty_like(p)
    run = 0
    for rank, i in enumerate(o):
        run = max(run, (len(p) - rank) * p[i])
        adj[i] = min(1, run)
    return adj


def ms(v, k):
    return f"{np.nanmean(v):.3f} ± {np.nanstd(v, ddof=1):.3f}" if k == "res1000" else f"{np.nanmean(v):.0f} ± {np.nanstd(v, ddof=1):.0f}"


md = ["# EB-ViTAL results (auto-generated by analyze.py)\n",
      f"Fairness check: {json.load(open('results/fairness.json'))}. The copied simulator reproduces every earlier reconstruction run bit-for-bit.\n"]

# ---- pre-registered hypotheses
md.append("## 1. Pre-registered hypotheses (static, L = 800, one-sided paired Wilcoxon, Holm across N)\n")
md.append("| Hypothesis | N | EB-ViTAL mean | Comparator mean | Mean gain | Median paired diff | p (raw) | p (Holm) | Supported |\n|---|---|---|---|---|---|---|---|---|")
verdicts = {}
for hid, comp, key in (("H1", "ViTAL", "FND"), ("H2", "LEACH (HSA)", "FND"), ("H3", "LEACH (HSA)", "HND")):
    x = [get("EB-ViTAL", N, key=key) for N in NS]
    y = [get(comp, N, key=key) for N in NS]
    p = [wilcoxon(a, b, alternative="greater").pvalue for a, b in zip(x, y)]
    ph = holm(p)
    verdicts[hid] = all(q < 0.05 for q in ph)
    for N, a, b, pr, pa in zip(NS, x, y, p, ph):
        md.append(f"| {hid}: EB-ViTAL {key} > {comp} | {N} | {a.mean():.0f} | {b.mean():.0f} | {100*(a.mean()/b.mean()-1):+.1f}% | "
                  f"{np.median(a-b):+.0f} | {pr:.2g} | {pa:.2g} | {'yes' if pa < 0.05 else 'no'} |")
md.append("\nOverall: " + ", ".join(f"{h} {'supported at all N' if v else 'NOT supported at all N'}" for h, v in verdicts.items()) + ".\n")


def table(title, labels, L, mobile):
    out = [f"## {title}\n"]
    for name, k in MET.items():
        out.append(f"### {name}\n\n| Protocol | " + " | ".join(f"N={N}" for N in NS) + " |\n|---|" + "---|" * len(NS))
        for lab in labels:
            if not len(get(lab, 100, L, mobile)):
                continue
            out.append(f"| {lab} | " + " | ".join(ms(get(lab, N, L, mobile, k), k) for N in NS) + " |")
        out.append("")
    return out


def gains(labels_ref, L, mobile):
    out = ["| EB-ViTAL vs | Metric | " + " | ".join(f"N={N}" for N in NS) + " |", "|---|---|" + "---|" * len(NS)]
    for ref in labels_ref:
        for name, k in list(MET.items())[:4]:
            cells = []
            for N in NS:
                a, b = get("EB-ViTAL", N, L, mobile, k), get(ref, N, L, mobile, k)
                cells.append(f"{100*(np.nanmean(a)/np.nanmean(b)-1):+.0f}%")
            out.append(f"| {ref} | {name} | " + " | ".join(cells) + " |")
    return out


md.append("## 2. Relative change of EB-ViTAL (mean over 30 runs), static, L = 800\n")
md += gains(["LEACH (random)", "LEACH (HSA)", "ViTAL", "ViTAL-noCDS"], 800, False)
md.append("\n## 3. Ablation (static, L = 800): change in full EB-ViTAL relative to each variant\n")
md.append("| Variant | Metric | " + " | ".join(f"N={N}" for N in NS) + " | Two-sided Wilcoxon p, Holm (all N) |\n|---|---|" + "---|" * len(NS) + "---|")
for lab in ABL[1:]:
    for name, k in list(MET.items())[:4]:
        cells, ps = [], []
        for N in NS:
            a, b = get("EB-ViTAL", N, key=k), get(lab, N, key=k)
            cells.append(f"{100*(np.nanmean(a)/np.nanmean(b)-1):+.0f}%")
            ok = ~np.isnan(a) & ~np.isnan(b)
            ps.append(wilcoxon(a[ok], b[ok]).pvalue if (a[ok] != b[ok]).any() else 1.0)
        md.append(f"| {lab} | {name} | " + " | ".join(cells) + f" | {', '.join(f'{q:.2g}' for q in holm(ps))} |")
md += [""] + table("4. Static, L = 800: all metrics (mean ± sd, 30 runs)", MAIN + ABL[1:], 800, False)
md += table("5. Static, L = 4000: all metrics", MAIN + ABL[1:], 4000, False)
md.append("### Relative change of EB-ViTAL, static, L = 4000\n")
md += gains(["LEACH (HSA)", "ViTAL"], 4000, False)
md += [""] + table("6. Mobile sink, L = 800", ["LEACH (HSA)", "ViTAL", "EB-ViTAL"], 800, True)
md.append("### Relative change of EB-ViTAL, mobile, L = 800\n")
md += gains(["LEACH (HSA)", "ViTAL"], 800, True)
md += [""] + table("7. Mobile sink, L = 4000", ["LEACH (HSA)", "ViTAL", "EB-ViTAL"], 4000, True)
md.append("### Relative change of EB-ViTAL, mobile, L = 4000\n")
md += gains(["LEACH (HSA)", "ViTAL"], 4000, True)
open("results/summary.md", "w").write("\n".join(md) + "\n")

