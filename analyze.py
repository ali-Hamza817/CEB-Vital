# coverage-over-time, S1, N = 300, 10 seeds
DEP = dict(np.load("results/test_deployments.npz"))
CFG = {"LEACH (HSA)": ("LEACH", {}), "DEEC": ("DEEC", {}), "ViTAL": ("ViTAL", {}),
       "EB-ViTAL": ("EB-ViTAL", {}), "CEB-ViTAL": ("EB-ViTAL", {"sched": "cov"})}


def trace(a):
    lab, s = a
    proto, kw = CFG[lab]
    t = []
    simulate(proto, 300, s, xy=DEP[f"hsa_100_300_{s}"], rmax=100000, side=100, bs0=(5, 5), L=800, cov_trace=t, **kw)
    return lab, np.array(t)


with Pool(50) as pool:
    tr = pool.map(trace, [(lab, s) for lab in CFG for s in range(1000, 1010)])
fig, ax = plt.subplots(figsize=(6.6, 3.8))
for lab in CFG:
    T = [t for l, t in tr if l == lab]
    n = max(len(t) for t in T)
    M = np.mean([np.pad(t, (0, n - len(t))) for t in T], 0)
    c, ls = STY[lab]
    ax.plot(np.arange(n), M, ls, color=c, lw=2, label=lab)
ax.set_xlabel("Round")
ax.set_ylabel("Covered fraction of field (mean of 10 seeds)")
ax.set_title("Sensing coverage over time, S1, N = 300", fontsize=9)
ax.legend(frameon=False, fontsize=8)
fig.tight_layout()
