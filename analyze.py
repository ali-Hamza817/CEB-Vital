md.append("| Scenario | Variant removed or replaced | " + " | ".join(f"N={N}" for N in NS) + " |\n|---|---|" + "---|" * len(NS))
ABL = [("EB-ViTAL", "CovSched removed (always on)"), ("EB-ViTAL + RandSleep", "coverage-aware selection replaced by random"),
       ("LEACH + CovSched", "EB clustering replaced by LEACH"), ("CEB-ViTAL -M3", "multi-hop removed")]
