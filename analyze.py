def panels(sc, labs, keys, fname, title):
    fig, axs = plt.subplots(1, len(keys), figsize=(3.5 * len(keys), 3.6))
    for ax, (name, k) in zip(axs, keys):
        for lab in labs:
            if not IDX.get((sc, lab, 100)):
                continue
            m = [mci(get(sc, lab, N, k)) for N in NS]
            c, ls = STY[lab]
            ax.errorbar(NS, [a for a, _ in m], yerr=[b for _, b in m], color=c, ls=ls, marker="o", ms=3,
                        lw=1.8, capsize=2, label=lab)
        ax.set_title(name, fontsize=9)
        ax.set_xlabel("No. of nodes")
    fig.suptitle(title, fontsize=10)
    fig.legend(*axs[0].get_legend_handles_labels(), loc="lower center", ncol=len(labs), fontsize=7.5, frameon=False)
    fig.tight_layout(rect=(0, 0.08, 1, 0.94))
    fig.savefig(f"figures/{fname}", dpi=150)
    fig.savefig(f"figures/{fname[:-4]}.pdf")
    plt.close(fig)


