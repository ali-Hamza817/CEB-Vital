M["CzeroSoneFive"] = f"{100*np.mean([r['C0'] for r in IDX[('S1', 'CEB-ViTAL', 500)]]):.0f}\\%"
v1 = lambda l, N: np.mean([r["FND"] for r in V1 if r["label"] == l and r["N"] == N and r["L"] == 800 and not r["mobile"]])
