"""Generates latex/numbers.tex, latex/tables/*.tex and copies figure PDFs, all from the run data."""
import os

import numpy as np
from scipy.stats import wilcoxon

from common import COMP, HERE, IDX, N3, NS, Q, R, ROOT, V1, best, gain, get, holm, mci

OUT = os.path.join(ROOT, "latex")
os.makedirs(f"{OUT}/tables", exist_ok=True)
os.makedirs(f"{OUT}/figures", exist_ok=True)


def pct(x):
    v = int(round(x))
    return "0\\%" if v == 0 else f"{v:+d}\\%".replace("-", "$-$")


def prange(xs):
    lo, hi = min(xs), max(xs)
    return pct(lo) if round(lo) == round(hi) else f"{pct(lo)} to {pct(hi)}"


def pmtex(v, scale=1.0, dec=0):
    m, c = mci(v)
    return f"{m/scale:.{dec}f}$\\pm${c/scale:.{dec}f}"


def lab(s):
    return s.replace(" -M3", " $-$M3")


def sci(p):
    m, e = f"{p:.1e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


def mean(sc, l, N, k):
    return np.nanmean(get(sc, l, N, k))


# ------------------------------------------------------------ macros
M = {}
M["NRuns"] = f"{len(R):,}".replace(",", "{,}")
M["NRob"] = f"{len(Q):,}".replace(",", "{,}")
M["NFair"] = "7{,}620"
M["TninetyBest"] = prange([gain(get("S1", "CEB-ViTAL", N, "T90"), get("S1", best("S1", N), N, "T90")) for N in NS])
