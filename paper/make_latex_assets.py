M["FNDVital"] = prange([gain(get("S1", "CEB-ViTAL", N, "FND"), get("S1", "ViTAL", N, "FND")) for N in NS])
M["CovBest"] = prange([gain(get("S1", "CEB-ViTAL", N, "cov_int"), get("S1", best("S1", N), N, "cov_int")) for N in NS])
M["ReadAll"] = prange([gain(get("S1", "CEB-ViTAL", N, "readings"), get("S1", c, N, "readings")) for N in NS for c in COMP])
