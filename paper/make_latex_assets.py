t = ["\\begin{tabular}{llccc}", "\\toprule", "Hyp. & Comparator & Gain ($N$=100--500) & Max.\\ Holm $p$ & Sig. \\\\", "\\midrule"]
for hid, k in (("H1", "T90"), ("H2", "cov_int"), ("H3", "FND")):
    ps, gs = [], []
    for c in COMP:
        for N in NS:
            a, b = get("S1", "CEB-ViTAL", N, k), get("S1", c, N, k)
            ps.append(wilcoxon(a, b, alternative="greater").pvalue)
            gs.append(gain(a, b))
    ph = holm(ps)
    for j, c in enumerate(COMP):
        sl = slice(5 * j, 5 * j + 5)
        t.append(f"{hid if j == 0 else ''} & {c} & {prange(gs[sl])} & {sci(ph[sl].max())} & {(ph[sl] < 0.05).sum()}/5 \\\\")
    t.append("\\midrule" if hid != "H3" else "\\bottomrule")
t.append("\\end{tabular}")
open(f"{OUT}/tables/tab_hyp.tex", "w").write("\n".join(t) + "\n")

