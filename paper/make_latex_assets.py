M["LNDcebH"] = f"{mean('S1', 'CEB-ViTAL', 100, 'LND'):.0f}"
M["LNDleachH"] = f"{mean('S1', 'LEACH (HSA)', 100, 'LND'):.0f}"
M["LNDvitalH"] = f"{mean('S1', 'ViTAL', 100, 'LND'):.0f}"
M["LNDcebF"] = f"{mean('S1', 'CEB-ViTAL', 500, 'LND'):.0f}"
M["LNDmaxF"] = f"{max(mean('S1', c, 500, 'LND') for c in COMP):.0f}"
M["TcebThree"] = f"{mean('S1', 'CEB-ViTAL', 300, 'T90'):.0f}"
M["TbestThree"] = f"{mean('S1', best('S1', 300), 300, 'T90'):.0f}"
M["MthreeSthree"] = prange([gain(get("S3", "CEB-ViTAL", N, "T90"), get("S3", "CEB-ViTAL -M3", N, "T90")) for N in NS])
M["LeachCovSone"] = prange([gain(get("S1", "CEB-ViTAL", N, "T90"), get("S1", "LEACH + CovSched", N, "T90")) for N in NS])


def rob(sc, f, k="T90"):
    out = []
    for N in N3:
        b = mean(sc, best(sc, N), N, k)
        S = [r for r in Q if r["scenario"] == sc and r["label"] == "CEB-ViTAL" and r["N"] == N and r["sleep_frac"] == f]
        out.append(100 * (np.mean([(r[k] if r[k] is not None else r["rounds"]) for r in S]) / b - 1))
    return out


M["RobSoneFone"] = prange(rob("S1", 1.0))
M["RobSthreeFone"] = prange(rob("S3", 1.0))
pall = []
for k in ("T90", "cov_int", "FND"):
    ps = [wilcoxon(get("S1", "CEB-ViTAL", N, k), get("S1", c, N, k), alternative="greater").pvalue for c in COMP for N in NS]
    pall.append(holm(ps).max())
M["PMax"] = sci(max(pall))[1:-1]          # bare math, used as $p\le\PMax$
with open(f"{OUT}/numbers.tex", "w") as f:
    f.write("% Auto-generated by paper/make_latex_assets.py from results/*.json. Do not edit by hand.\n")
    for k, v in M.items():
        f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")

